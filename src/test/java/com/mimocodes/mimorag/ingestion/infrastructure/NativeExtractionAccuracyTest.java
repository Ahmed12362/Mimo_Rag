package com.mimocodes.mimorag.ingestion.infrastructure;

import java.io.InputStream;
import java.nio.file.Path;
import java.text.Normalizer;
import java.time.Duration;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.mimocodes.mimorag.ingestion.application.LineBuilder;
import com.mimocodes.mimorag.ingestion.application.NativePage;
import com.mimocodes.mimorag.ingestion.application.NativeTextExtractor.NativePdf;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Regression test for native text quality on the committed synthetic corpus (generated by
 * benchmarks/ocr/generate_corpus.py). Character error rate uses the same normalisation as the 2a OCR benchmark (NFKC,
 * tatweel removed, whitespace collapsed), so results are comparable with docs/benchmarks/ocr-benchmark-2a.md.
 * <p>
 * Targets are the slice 2c acceptance criteria. The fully diacritised page has no target: it is reported, and if it
 * is poor the page must be flagged for review (see PageClassifier tests).
 */
class NativeExtractionAccuracyTest {

	private static final Path CORPUS = Path.of("src/test/resources/corpus/synthetic/digital");

	/** Maximum character error rate per page (acceptance criteria). */
	private static final Map<String, Double> TARGETS = new LinkedHashMap<>();

	static {
		TARGETS.put("en_leave_serif", 0.0);
		TARGETS.put("en_expenses_sans10", 0.0);
		TARGETS.put("ar_sick_naskh", 0.0);
		TARGETS.put("ar_hiring_sans10", 0.0);
		TARGETS.put("mixed_ar_en_naskh", 0.02);
		TARGETS.put("mixed_lines_sans", 0.02);
		TARGETS.put("ar_table_naskh", 0.10);
		TARGETS.put("ar_policy_amiri", 0.05);
	}

	private final PdfBoxNativeTextExtractor extractor = new PdfBoxNativeTextExtractor();

	@Test
	void characterErrorRateMeetsTheTargets() throws Exception {
		JsonNode truth = groundTruth();
		Map<String, Double> measured = new LinkedHashMap<>();
		StringBuilder report = new StringBuilder("\nNative extraction CER (LineBuilder):\n");
		for (String page : truth.propertyNames()) {
			List<String> expected = new ArrayList<>();
			truth.get(page).get("lines").forEach(line -> expected.add(normalise(line.asString())));
			String actual = extract(page);
			List<String> actualLines = actual.lines().map(NativeExtractionAccuracyTest::normalise)
				.filter(l -> !l.isEmpty())
				.toList();
			double cer = cer(String.join("\n", expected), String.join("\n", actualLines));
			measured.put(page, cer);
			report.append(String.format("  %-22s %6.2f%%  (target %s)%n", page, cer * 100,
					TARGETS.containsKey(page) ? String.format("%.0f%%", TARGETS.get(page) * 100) : "reported only"));
			if (cer > TARGETS.getOrDefault(page, 1.0) || cer > 0) {
				for (int i = 0; i < Math.max(expected.size(), actualLines.size()); i++) {
					String e = i < expected.size() ? expected.get(i) : "";
					String a = i < actualLines.size() ? actualLines.get(i) : "";
					if (!e.equals(a)) {
						report.append("      expected: ").append(e).append("\n      actual:   ").append(a).append('\n');
					}
				}
			}
		}
		System.out.println(report);
		java.nio.file.Files.writeString(Path.of("target/native-extraction-accuracy.txt"), report,
				java.nio.charset.StandardCharsets.UTF_8);
		TARGETS.forEach((page, target) -> assertThat(measured.get(page)).as("CER of %s", page)
			.isLessThanOrEqualTo(target));
	}

	private String extract(String page) {
		try (NativePdf pdf = extractor.open(CORPUS.resolve(page + ".pdf"))) {
			NativePage nativePage = pdf.page(1, Duration.ofSeconds(30));
			return LineBuilder.build(nativePage.glyphs()).text();
		}
	}

	private static JsonNode groundTruth() throws Exception {
		try (InputStream in = java.nio.file.Files.newInputStream(CORPUS.resolve("ground-truth.json"))) {
			return JsonMapper.builder().build().readTree(in);
		}
	}

	static String normalise(String text) {
		String nfkc = Normalizer.normalize(text, Normalizer.Form.NFKC).replace("ـ", "");
		return nfkc.replaceAll("\\s+", " ").strip();
	}

	static double cer(String expected, String actual) {
		return expected.isEmpty() ? (actual.isEmpty() ? 0 : 1) : (double) levenshtein(expected, actual) / expected.length();
	}

	private static int levenshtein(String a, String b) {
		int[] previous = new int[b.length() + 1];
		int[] current = new int[b.length() + 1];
		for (int j = 0; j <= b.length(); j++) {
			previous[j] = j;
		}
		for (int i = 1; i <= a.length(); i++) {
			current[0] = i;
			for (int j = 1; j <= b.length(); j++) {
				int cost = a.charAt(i - 1) == b.charAt(j - 1) ? 0 : 1;
				current[j] = Math.min(Math.min(current[j - 1] + 1, previous[j] + 1), previous[j - 1] + cost);
			}
			int[] swap = previous;
			previous = current;
			current = swap;
		}
		return previous[b.length()];
	}

}
